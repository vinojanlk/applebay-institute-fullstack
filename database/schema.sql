CREATE TABLE IF NOT EXISTS courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    description VARCHAR(2000),
    fee NUMERIC(10, 2) NOT NULL CHECK (fee > 0),
    level VARCHAR(20) NOT NULL,
    duration_months INTEGER NOT NULL CHECK (duration_months > 0),
    status VARCHAR(20) NOT NULL,
    CONSTRAINT ck_courses_level CHECK (level IN ('HND', 'CERTIFICATE')),
    CONSTRAINT ck_courses_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE IF NOT EXISTS batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    course_id BIGINT NOT NULL REFERENCES courses (id),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    status VARCHAR(20) NOT NULL,
    CONSTRAINT ck_batches_status
        CHECK (status IN ('PLANNED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED'))
);

CREATE SEQUENCE IF NOT EXISTS student_number_seq START WITH 1;

CREATE TABLE IF NOT EXISTS students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_number VARCHAR(30) NOT NULL UNIQUE,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    nic VARCHAR(20) NOT NULL UNIQUE,
    email VARCHAR(254) NOT NULL,
    phone VARCHAR(25),
    address VARCHAR(500),
    date_of_birth DATE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_students_email_lower
    ON students (LOWER(email));

CREATE TABLE IF NOT EXISTS enrollments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students (id),
    course_id BIGINT NOT NULL REFERENCES courses (id),
    batch_id BIGINT NOT NULL REFERENCES batches (id),
    enrolled_on DATE NOT NULL,
    status VARCHAR(20) NOT NULL,
    CONSTRAINT uk_enrollments_student_course_batch
        UNIQUE (student_id, course_id, batch_id),
    CONSTRAINT ck_enrollments_status
        CHECK (status IN ('ACTIVE', 'COMPLETED', 'WITHDRAWN'))
);

CREATE TABLE IF NOT EXISTS attendance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrollment_id BIGINT NOT NULL REFERENCES enrollments (id),
    attendance_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL,
    remarks VARCHAR(500),
    CONSTRAINT uk_attendance_enrollment_date
        UNIQUE (enrollment_id, attendance_date),
    CONSTRAINT ck_attendance_status
        CHECK (status IN ('PRESENT', 'ABSENT', 'LATE'))
);

CREATE SEQUENCE IF NOT EXISTS payment_receipt_seq START WITH 1;

CREATE TABLE IF NOT EXISTS payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrollment_id BIGINT NOT NULL REFERENCES enrollments (id),
    receipt_number VARCHAR(40) NOT NULL UNIQUE,
    amount NUMERIC(10, 2) NOT NULL CHECK (amount > 0),
    paid_on DATE NOT NULL,
    payment_method VARCHAR(30) NOT NULL,
    reference VARCHAR(100),
    CONSTRAINT ck_payments_payment_method
        CHECK (payment_method IN ('CASH', 'BANK_TRANSFER', 'CARD', 'ONLINE'))
);
